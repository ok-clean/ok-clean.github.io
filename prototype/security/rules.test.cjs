const fs = require('node:fs');
const assert = require('node:assert/strict');
const { initializeTestEnvironment, assertFails, assertSucceeds } = require('@firebase/rules-unit-testing');
const { doc, collection, setDoc, getDoc, getDocs, updateDoc, deleteDoc, serverTimestamp } = require('firebase/firestore');
const {createQuote,listQuotes,setStatus} = require('./quote-service.cjs');
(async () => {
 const env = await initializeTestEnvironment({projectId:'demo-okclean-matching',firestore:{rules:fs.readFileSync('prototype/security/firestore.rules','utf8')}});
 try {
  const anon=env.authenticatedContext('customer-1',{firebase:{sign_in_provider:'anonymous'}}).firestore();
  const other=env.authenticatedContext('customer-2',{firebase:{sign_in_provider:'anonymous'}}).firestore();
  const admin=env.authenticatedContext('admin-test',{admin:true}).firestore();
  const stranger=env.unauthenticatedContext().firestore();
  const partner=env.authenticatedContext('partner-1',{email_verified:true,firebase:{sign_in_provider:'password'}}).firestore();
  const partner2=env.authenticatedContext('partner-2',{email_verified:true,firebase:{sign_in_provider:'password'}}).firestore();
  const unverified=env.authenticatedContext('unverified',{email_verified:false,firebase:{sign_in_provider:'password'}}).firestore();
  const profile={company:'가상청소업체',areas:['춘천','가평'],specialties:['입주·이사 청소'],status:'검토중'};
  await assertFails(setDoc(doc(unverified,'partner_profiles','unverified'),profile));
  await assertFails(setDoc(doc(anon,'partner_profiles','customer-1'),profile));
  await assertFails(setDoc(doc(partner,'partner_profiles','partner-1'),{...profile,status:'승인'}));
  await assertFails(setDoc(doc(partner,'partner_profiles','partner-2'),profile));
  await assertFails(setDoc(doc(partner,'partner_profiles','partner-1'),{...profile,areas:['허위지역']}));
  await assertSucceeds(setDoc(doc(partner,'partner_profiles','partner-1'),profile));
  await assertSucceeds(getDoc(doc(partner,'partner_profiles','partner-1')));
  await assertFails(getDoc(doc(partner2,'partner_profiles','partner-1')));
  await assertFails(getDocs(collection(partner,'partner_profiles')));
  await assertSucceeds(getDocs(collection(admin,'partner_profiles')));
  await assertFails(updateDoc(doc(partner,'partner_profiles','partner-1'),{status:'승인'}));
  await assertFails(updateDoc(doc(partner,'partner_profiles','partner-1'),{specialties:['허위전문분야']}));
  await assertSucceeds(updateDoc(doc(partner,'partner_profiles','partner-1'),{areas:['춘천','홍천']}));
  await assertSucceeds(updateDoc(doc(admin,'partner_profiles','partner-1'),{status:'승인'}));
  await assertFails(updateDoc(doc(admin,'partner_profiles','partner-1'),{company:'임의 변경'}));
  await assertFails(deleteDoc(doc(partner,'partner_profiles','partner-1')));
  await assertFails(getDocs(collection(partner,'quote_requests')));
  const payload={service:'입주·이사 청소',area:'춘천',size:25,date:new Date(Date.now() + 7 * 86400000),name:'테스트',phone:'01000000000',consentVersion:'test-v1',consentAt:serverTimestamp(),createdAt:serverTimestamp(),ownerUid:'customer-1',status:'신규'};
  await assertSucceeds(setDoc(doc(anon,'quote_requests','a'),payload));
  await assertFails(setDoc(doc(anon,'quote_requests','a'),payload));
  await assertFails(getDoc(doc(anon,'quote_requests','a')));
  await assertFails(getDoc(doc(other,'quote_requests','a')));
  await assertFails(getDocs(collection(stranger,'quote_requests')));
  await assertFails(setDoc(doc(anon,'quote_requests','b'),{...payload,ownerUid:'customer-2'}));
  await assertFails(setDoc(doc(anon,'quote_requests','c'),{...payload,status:'예약확정'}));
  await assertFails(setDoc(doc(anon,'quote_requests','d'),{...payload,extra:'unexpected'}));
  await assertFails(setDoc(doc(anon,'quote_requests','e'),{...payload,size:1000}));
  await assertFails(setDoc(doc(anon,'quote_requests','noconsent'),{...payload,consentVersion:''}));
  await assertFails(setDoc(doc(anon,'quote_requests','badphone'),{...payload,phone:'wrong'}));
  await assertFails(setDoc(doc(anon,'quote_requests','past'),{...payload,date:new Date(Date.now()-86400000)}));
  await assertFails(setDoc(doc(anon,'quote_requests','invalid'),{...payload,date:'2099-99-99'}));
  await assertFails(setDoc(doc(anon,'quote_requests','far'),{...payload,date:new Date(Date.now()+400*86400000)}));
  await assertFails(updateDoc(doc(anon,'quote_requests','a'),{status:'예약확정'}));
  await assertSucceeds(getDoc(doc(admin,'quote_requests','a')));
  const adminList = await assertSucceeds(getDocs(collection(admin,'quote_requests')));
  if (adminList.size !== 1 || adminList.docs[0].data().status !== '신규') throw new Error('관리자 요청 목록 검증 실패');
  await assertSucceeds(updateDoc(doc(admin,'quote_requests','a'),{status:'상담중'}));
  const changed = await assertSucceeds(getDoc(doc(admin,'quote_requests','a')));
  if (changed.data().status !== '상담중') throw new Error('관리자 상태 갱신 검증 실패');
  await assertFails(updateDoc(doc(admin,'quote_requests','a'),{phone:'01011112222'}));
  await assertFails(deleteDoc(doc(admin,'quote_requests','a')));
  const form={service:'입주·이사 청소',area:'춘천',size:25,date:new Date(Date.now()+86400000),name:'가상고객',phone:'01000000000',consent:true};
  await assert.rejects(createQuote(anon,'customer-1','ui-invalid',{...form,consent:false}));
  await assert.rejects(createQuote(anon,'customer-1','invalid-calendar',{...form,date:'2025-02-29'}));
  const tomorrowKst = new Date(Date.now()+33*3600000).toISOString().slice(0,10);
  await createQuote(anon,'customer-1','calendar-date',{...form,date:tomorrowKst});
  const calendarRecord = await getDoc(doc(admin,'quote_requests','calendar-date'));
  assert.equal(calendarRecord.data().date.toDate().toISOString(), tomorrowKst+'T14:59:59.999Z');
  const receipt=await createQuote(anon,'customer-1','ui-example',form);
  if(receipt.id !== 'ui-example') throw new Error('접수 식별자 불일치');
  await assertFails(createQuote(anon,'customer-1','ui-example',form));
  await assertFails(listQuotes(anon));
  const requests=await listQuotes(admin);
  if(!requests.some(x=>x.id==='ui-example' && x.status==='신규')) throw new Error('관리자 목록 누락');
  await setStatus(admin,'ui-example','상담중');
  if(!(await listQuotes(admin)).some(x=>x.id==='ui-example' && x.status==='상담중')) throw new Error('관리자 상태 저장 실패');
  console.log('PASS create-only, validation, admin access and write separation');
 } finally {await env.cleanup();}
})().catch(err=>{console.error(err);process.exit(1)});

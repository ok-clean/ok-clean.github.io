const assert=require('node:assert/strict');
const {createDemoMatching}=require('./matching-demo.cjs');
const m=createDemoMatching();
assert.throws(()=>m.registerPartner('../bad','업체'));
assert.throws(()=>m.createRequest('../bad',{service:'청소',area:'춘천'}));
m.registerPartner('p1','가상 업체 A');m.registerPartner('p2','가상 업체 B');
m.createRequest('r1',{service:'입주·이사 청소',area:'춘천'});
assert.throws(()=>m.assign('r1','p1'));
m.approvePartner('p1');m.assign('r1','p1');
assert.throws(()=>m.offer('r1','p2',100000));
assert.throws(()=>m.offer('r1','p1',0));
m.offer('r1','p1',250000);
assert.throws(()=>m.offer('r1','p1',200000));
assert.deepEqual(m.compare('r1'),[{company:'가상 업체 A',price:250000}]);
m.revokePartner('p1');
assert.deepEqual(m.compare('r1'),[]);
assert.throws(()=>m.offer('r1','p1',260000));
m.approvePartner('p1');m.assign('r1','p1');
assert.deepEqual(m.compare('r1'),[]);
m.offer('r1','p1',260000);
m.unassign('r1','p1');
assert.deepEqual(m.compare('r1'),[]);
m.assign('r1','p1');
assert.throws(()=>m.setStatus('r1','예약확정'));
m.offer('r1','p1',270000);
m.setStatus('r1','검토중');
assert.throws(()=>m.setStatus('r1','예약확정'));
m.setStatus('r1','견적도착');
m.setStatus('r1','예약확정');
assert.throws(()=>m.setStatus('r1','예약확정'));
assert.throws(()=>m.assign('r1','p1'));
assert.throws(()=>m.offer('r1','p1',280000));
assert.throws(()=>m.setStatus('r1','신규'));
m.setStatus('r1','작업완료');
assert.throws(()=>m.setStatus('r1','작업완료'));
assert.throws(()=>m.setStatus('r1','검토중'));
assert.throws(()=>m.offer('r1','p1',290000));
console.log('PASS demo matching assignment and offer isolation');
